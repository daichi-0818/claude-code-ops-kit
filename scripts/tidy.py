#!/usr/bin/env python3
"""Idempotent daily tidy for a notes/knowledge tree.

Three jobs, all safe to re-run:
  1. Monthly archive of a running daily-notes file: every dated section
     (## YYYY-MM-DD) that is NOT in the current month is moved out to
     <archive-dir>/NOTES_YYYY-MM.md. Keeps the live file to the current month
     only, so it never grows unbounded.
  2. INDEX.md regeneration for one or more directories (subdir table with file
     counts + last-modified, plus a most-recently-modified list of top-level
     .md files). Regenerated every run so the index never drifts from reality.
  3. Log rotation: files named <prefix>YYYYMMDD*.<ext> in a log dir are moved
     into YYYY-MM/ subfolders once they leave the current month.

Safety design:
- --dry-run prints the planned moves/rewrites without doing them.
- The daily-notes file gets a full one-time backup into the archive dir before
  it is ever rewritten.
- A lock directory guards against concurrent runs.
- Only date headings (^## YYYY-MM-DD) are interpreted; every other line stays
  attached to the section above it.

This is the "keep the workspace from silently rotting" component: an unbounded
notes file and a stale hand-maintained index are slow-motion failures a
long-running agent setup accumulates.

Usage:
  python3 tidy.py --notes ~/notes/DAILY.md --archive-dir ~/notes/archive \\
      --index-dir ~/notes --log-dir ~/notes/logs [--log-prefix log_] [--dry-run]
"""
import argparse
import os
import re
import shutil
from datetime import datetime

NOW = datetime.now()
CUR_MONTH = NOW.strftime("%Y-%m")
DATE_HEAD = re.compile(r"^## (\d{4}-\d{2})-\d{2}")

actions = []
DRY = False


def log(msg):
    actions.append(msg)
    print(("[DRY] " if DRY else "") + msg)


def archive_notes(notes, archive_dir):
    if not notes:
        return
    if not os.path.exists(notes):
        log(f"notes file not found ({notes}) — skip")
        return
    os.makedirs(archive_dir, exist_ok=True)
    with open(notes, encoding="utf-8") as f:
        lines = f.readlines()

    # One-time full backup (only if none exists yet).
    backup = f"{archive_dir}/NOTES_full_backup_{NOW.strftime('%Y%m%d')}.md"
    existing_backups = [x for x in os.listdir(archive_dir) if x.startswith("NOTES_full_backup_")]
    if not existing_backups and not DRY:
        shutil.copy2(notes, backup)
        log(f"full backup created: {backup}")

    keep, sections = [], {}  # sections: month -> list of lines
    cur_target = keep  # preamble before the first date heading stays in `keep`
    for line in lines:
        m = DATE_HEAD.match(line)
        if m:
            month = m.group(1)
            cur_target = keep if month == CUR_MONTH else sections.setdefault(month, [])
        cur_target.append(line)

    if not sections:
        log("notes: no non-current-month sections — no change")
        return

    for month, sec in sorted(sections.items()):
        dest = f"{archive_dir}/NOTES_{month}.md"
        n = sum(1 for line in sec if DATE_HEAD.match(line))
        log(f"notes: {month} — {n} day(s) ({len(sec)} lines) -> {os.path.basename(dest)}")
        if not DRY:
            with open(dest, "a", encoding="utf-8") as f:
                f.write(f"\n<!-- tidy {NOW.strftime('%Y-%m-%d %H:%M')} archived -->\n")
                f.writelines(sec)
    log(f"notes: {len(lines)} lines -> {len(keep)} lines")
    if not DRY:
        tmp = notes + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.writelines(keep)
        os.replace(tmp, notes)


def gen_index(target_dir, title):
    if not os.path.isdir(target_dir):
        log(f"index: {target_dir} not found — skip")
        return
    idx = f"{target_dir}/INDEX.md"
    out = [f"# {title} INDEX (auto-generated {NOW.strftime('%Y-%m-%d %H:%M')})",
           "",
           "> Regenerated by tidy.py on every run. Manual edits are overwritten —"
           " keep durable notes inside individual files instead.",
           ""]
    entries = sorted(os.listdir(target_dir))
    dirs = [e for e in entries if os.path.isdir(os.path.join(target_dir, e)) and not e.startswith(".")]
    files = [e for e in entries if e.endswith(".md") and e != "INDEX.md"]

    out += ["## Subdirectories", "", "| Directory | Files | Last modified |", "|---|---:|---|"]
    for d in dirs:
        full = os.path.join(target_dir, d)
        count, newest = 0, 0.0
        for r, _dn, fn in os.walk(full):
            for x in fn:
                if x.startswith("."):
                    continue
                count += 1
                try:
                    newest = max(newest, os.path.getmtime(os.path.join(r, x)))
                except OSError:
                    pass
        newest_s = datetime.fromtimestamp(newest).strftime("%Y-%m-%d") if newest else "-"
        out.append(f"| {d}/ | {count} | {newest_s} |")

    out += ["", f"## Top-level .md files ({len(files)})", ""]
    files_mt = sorted(files, key=lambda x: os.path.getmtime(os.path.join(target_dir, x)), reverse=True)
    for x in files_mt:
        mt = datetime.fromtimestamp(os.path.getmtime(os.path.join(target_dir, x))).strftime("%Y-%m-%d")
        out.append(f"- [{x}]({x.replace(' ', '%20')}) — {mt}")
    log(f"{title}: INDEX regenerated (dirs {len(dirs)} / md {len(files)})")
    if not DRY:
        with open(idx, "w", encoding="utf-8") as f:
            f.write("\n".join(out) + "\n")


def rotate_logs(log_dir, prefix):
    if not log_dir or not os.path.isdir(log_dir):
        return
    pat = re.compile(r"^" + re.escape(prefix) + r"(\d{4})(\d{2})\d{2}")
    moved = {}
    for name in sorted(os.listdir(log_dir)):
        m = pat.match(name)
        if not m:
            continue
        month = f"{m.group(1)}-{m.group(2)}"
        if month == CUR_MONTH:
            continue
        sub = os.path.join(log_dir, month)
        if not DRY:
            os.makedirs(sub, exist_ok=True)
            os.rename(os.path.join(log_dir, name), os.path.join(sub, name))
        moved[month] = moved.get(month, 0) + 1
    if moved:
        log("log rotation: " + ", ".join(f"{k}: {v}" for k, v in sorted(moved.items())))
    else:
        log("logs: nothing to rotate")


def main():
    global DRY
    ap = argparse.ArgumentParser(description="Idempotent daily tidy for a notes/knowledge tree")
    ap.add_argument("--notes", help="Running daily-notes markdown file to month-archive")
    ap.add_argument("--archive-dir", help="Where monthly notes archives go (required with --notes)")
    ap.add_argument("--index-dir", action="append", default=[],
                    help="Directory to (re)generate an INDEX.md for; repeatable")
    ap.add_argument("--log-dir", help="Directory whose dated log files get rotated into YYYY-MM/")
    ap.add_argument("--log-prefix", default="log_", help="Filename prefix of log files (default: log_)")
    ap.add_argument("--lock", default="/tmp/tidy.lock", help="Lock directory path")
    ap.add_argument("--run-log", default=os.path.expanduser("~/Library/Logs/tidy.log"),
                    help="Append a one-line run summary here")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    DRY = args.dry_run

    if args.notes and not args.archive_dir:
        ap.error("--notes requires --archive-dir")

    try:
        os.mkdir(args.lock)
    except FileExistsError:
        print("another run in progress (lock present) — skip")
        return
    try:
        archive_notes(args.notes, args.archive_dir)
        for d in args.index_dir:
            gen_index(os.path.expanduser(d), os.path.basename(os.path.normpath(d)) or "root")
        rotate_logs(args.log_dir, args.log_prefix)
        if not DRY:
            try:
                os.makedirs(os.path.dirname(args.run_log), exist_ok=True)
                with open(args.run_log, "a") as f:
                    f.write(f"{NOW.strftime('%Y-%m-%d %H:%M:%S')} " + " | ".join(actions) + "\n")
            except OSError:
                pass
    finally:
        os.rmdir(args.lock)


if __name__ == "__main__":
    main()
